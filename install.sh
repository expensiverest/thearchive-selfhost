#!/usr/bin/env bash
# The Archive - one-command self-host installer.
#
# Checks Docker, generates strong secrets, writes .env (mode 600), pulls the published images,
# starts the stack, waits for it to become healthy and creates the first owner account.
#
# Usage:
#   bash install.sh
#   OWNER_EMAIL=you@example.com OWNER_NAME="Your Name" bash install.sh
#
# Environment overrides:
#   OWNER_EMAIL, OWNER_NAME    first owner account (prompted if unset)
#   ARCHIVE_ROOT               data directory (default: ./data next to this script)
#   ARCHIVE_VERSION            image tag (default: latest; set e.g. 0.1.0 to pin)
#   PUBLIC_BASE_URL            public HTTPS URL for invitation links (optional)
#   API_BIND_ADDR              publish address (default: 127.0.0.1)
#
# Re-running is refused if .env already exists (set FORCE=1 to overwrite - this does NOT delete
# data, but it will regenerate POSTGRES_PASSWORD and lock you out of an existing database).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
die() {
  printf '\n\033[31merror:\033[0m %s\n' "$*" >&2
  exit 1
}

# --- prerequisites ----------------------------------------------------------------------------
command -v docker >/dev/null 2>&1 || die "Docker is not installed. See https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "The Docker Compose plugin is missing (docker compose). Install it and retry."
docker info >/dev/null 2>&1 || die "Cannot talk to the Docker daemon. Is it running? Is your user in the 'docker' group?"

if [ -f .env ] && [ "${FORCE:-}" != "1" ]; then
  die ".env already exists. Use 'bash upgrade.sh' to update, or FORCE=1 bash install.sh to start over."
fi

# --- collect the first owner ------------------------------------------------------------------
OWNER_EMAIL="${OWNER_EMAIL:-}"
OWNER_NAME="${OWNER_NAME:-}"
if [ -z "$OWNER_EMAIL" ]; then
  read -rp "Email for the first owner account: " OWNER_EMAIL
fi
[ -n "$OWNER_EMAIL" ] || die "an owner email is required"
if [ -z "$OWNER_NAME" ]; then
  read -rp "Display name for the first owner account: " OWNER_NAME
fi
[ -n "$OWNER_NAME" ] || die "an owner display name is required"

ARCHIVE_ROOT="${ARCHIVE_ROOT:-$SCRIPT_DIR/data}"
ARCHIVE_VERSION="${ARCHIVE_VERSION:-latest}"
HOST_UID="${HOST_UID:-$(id -u)}"
HOST_GID="${HOST_GID:-$(id -g)}"
API_BIND_ADDR="${API_BIND_ADDR:-127.0.0.1}"
PUBLIC_BASE_URL="${PUBLIC_BASE_URL:-}"

# --- generate secrets -------------------------------------------------------------------------
# hex keeps the value safe inside the DATABASE_URL connection string.
gen() { openssl rand -hex "${1:-32}" 2>/dev/null || head -c "$((${1:-32} * 2))" /dev/urandom | od -An -tx1 | tr -d ' \n'; }
POSTGRES_PASSWORD="$(gen 32)"

say "Creating data directories under $ARCHIVE_ROOT"
mkdir -p "$ARCHIVE_ROOT"/{db,storage,run}

say "Writing .env (mode 600)"
umask 077
cat >.env <<EOF
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file secret (mode 600).
ARCHIVE_VERSION=$ARCHIVE_VERSION
ARCHIVE_ROOT=$ARCHIVE_ROOT
HOST_UID=$HOST_UID
HOST_GID=$HOST_GID
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
API_BIND_ADDR=$API_BIND_ADDR
PUBLIC_BASE_URL=$PUBLIC_BASE_URL
DEFAULT_USER_QUOTA_BYTES=0
MIN_APP_VERSION=0.0.0
SMTP_URL=
MAIL_FROM=
EOF
chmod 600 .env
umask 022

compose() { docker compose --env-file .env -f compose.yaml "$@"; }

# --- pull and start ---------------------------------------------------------------------------
say "Pulling images (tag: $ARCHIVE_VERSION)"
compose pull

say "Starting the stack"
compose up -d

say "Waiting for the API to become healthy"
api_id="$(compose ps -q api)"
for i in $(seq 1 60); do
  status="$(docker inspect --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$api_id" 2>/dev/null || echo none)"
  [ "$status" = "healthy" ] && break
  if [ "$status" = "unhealthy" ]; then
    compose logs --tail 40 api
    die "the API reported unhealthy; logs above"
  fi
  sleep 2
done
[ "$status" = "healthy" ] || {
  compose logs --tail 40 api
  die "the API did not become healthy in time; logs above"
}
say "Stack is healthy."
compose ps

# --- first owner account ----------------------------------------------------------------------
say "Creating the first owner account for $OWNER_EMAIL"
compose exec -T api node services/api/src/cli.ts create-owner --email "$OWNER_EMAIL" --name "$OWNER_NAME"

cat <<EOF

Done.

Next steps:
  1. If you saw a one-time password above, store it now - it is not shown again.
  2. Install the app, connect to http://<this-host>:8130 (or your public HTTPS URL) and sign in.
  3. For public HTTPS and email, see docs/self-hosting.md.
  4. Set up backups: docs/backup-restore.md.
EOF
